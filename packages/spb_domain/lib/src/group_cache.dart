import 'package:spb_models/spb_models.dart';

/// 对话列表缓存（issue #26 切片 A）。
///
/// ## 为什么抽象成接口（而不是让页面直接用 drift）
///
/// 与 [SyncStateStore] 同一模式：持久化在 `spb_data`，而消费方（`GroupListPage`）
/// 在 `spb_features`。`spb_domain` 不能依赖 `spb_data`（见 AGENTS.md §3 的分层
/// 规则），故契约放这里，页面只依赖接口，单测可注入内存实现。
///
/// ## 语义总纲：**可丢弃数据**
///
/// 本缓存的每一处失败路径都必须**静默降级**，理由与 [SyncStateStore]（不可丢）
/// 刚好相反：
///
/// | | `SyncStateStore` | `GroupCacheStore` |
/// |---|---|---|
/// | 数据性质 | 不可丢（丢了会全量重下文件） | **可丢弃**（丢了只是下次断网白屏） |
/// | 读失败 | 返回 `SyncState.empty`（按首次同步） | 返回**空列表** |
/// | 写失败 | 抛 `StorageError` | **不抛**（记日志即可） |
///
/// 若这里也抛异常，磁盘满 / 库损坏就会把「对话列表能打开」变成「对话列表报错」
/// ——而缓存的存在意义恰恰是**在坏环境下让应用可用**。
///
/// 设计依据见 `docs/offline-cache-design.md`（§3.1 表结构、§3.3 整表替换、
/// §3.4 为什么不用 TTL、§4 写路径、§8.3 回落逻辑）。
abstract interface class GroupCacheStore {
  /// 读该用户的缓存列表。
  ///
  /// **无缓存 / 读失败一律返回空列表，不抛异常**（见类文档的语义总纲）。
  /// 空列表与「有缓存但服务端确实没有对话」不可区分——这是有意的：两者的
  /// 界面表现相同（空态），而区分它们需要额外一次网络请求。
  ///
  /// 顺序：按服务端 `updated_at` **降序**（与 `GET /chat/groups` 的默认排序
  /// 一致）。缓存是列表的投影，顺序不一致会让「离线看到的第一条」与「在线看到
  /// 的第一条」不同，用户会以为数据错了。
  Future<List<ChatGroup>> load(String userId);

  /// **整表替换**该用户的缓存。
  ///
  /// ## 为什么必须是「先删后插」而不是逐行 upsert
  ///
  /// 这是从 [SyncStateStore.save] 学到的教训（其类文档已写明）：
  ///
  /// > 若只做 upsert 而不删，远端已删除的文件会永远留在表里。
  ///
  /// 同样的陷阱在 group 列表上是：**服务端删了一个 group，逐行 upsert 的缓存
  /// 会永远显示它**——用户点进去得到 404，且没有任何机制能让它消失，因为
  /// `group_updated` 的删除通知只在**在线时**收到，而缓存的用途正是离线。
  ///
  /// 实现必须在**单个事务**里完成删除与插入，否则中途失败会留下「删了旧的、
  /// 没插新的」的空缓存。
  ///
  /// [groups] 为空时等价于清空该用户缓存（合法：服务端确实一个对话都没有）。
  Future<void> save(String userId, List<ChatGroup> groups);

  /// 清空该用户的缓存（登出时调用）。
  ///
  /// ⚠️ **不得**影响同步状态（[SyncStateStore.resetAll]）：换账号与「交付物同步
  /// 目录绑定」无关，清了会让用户下次同步全量重下。
  ///
  /// 实现层也可以选择不提供此方法（靠 [load]/[save] 的 `userId` 隔离即可保证
  /// 不串号）——它是给「登出时主动释放空间」用的可选优化，不是正确性前提。
  Future<void> clear(String userId);

  /// 上次写入时刻；从未写过返回 null。
  ///
  /// ## 为什么单独一个方法（而不是让 [load] 返回带时间的包装）
  ///
  /// 陈旧提示只有**列表页的回落分支**需要，而 [load] 的其它调用点（如「点进
  /// 对话再返回」）不关心。把它塞进 `load` 的返回值会让所有调用点都要处理它。
  ///
  /// 读失败返回 null（与 [load] 的取向一致：不抛）。
  Future<DateTime?> lastFetchedAt(String userId);
}
